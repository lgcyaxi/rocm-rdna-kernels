"""Pack the gfx1010 Tensile assembly GEMM kernels into one code object.

Copies the kernel sources listed in gfx1010/asm_gemm/kernels.json out of a
Tensile benchmark directory (optional), assembles them with the same flags
Tensile uses, links them into gfx1010/asm_gemm/gfx1010_asm_gemm.co, and writes
the C array that PyTorch embeds (gfx1010/asm_gemm/hsaco.inc).
"""

import argparse
import json
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "gfx1010" / "asm_gemm"
SRC_DIR = OUT_DIR / "src"
KERNEL_RE = re.compile(r"^\.amdhsa_kernel (\S+)$", re.MULTILINE)


def copy_sources(tensile_dir: Path, names: set[str]) -> None:
    found: dict[str, str] = {}
    pattern = "1_BenchmarkProblems/*/00_Final/source/build_tmp/SOURCE/assembly/*.s"
    for path in tensile_dir.glob(pattern):
        text = path.read_text(encoding="utf-8")
        for name in KERNEL_RE.findall(text):
            if name in names:
                found[name] = text
    missing = names - found.keys()
    if missing:
        raise SystemExit(f"kernels not found under {tensile_dir}: {sorted(missing)}")
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in found.items():
        (SRC_DIR / f"{name}.s").write_text(text, encoding="utf-8", newline="\n")


def build_code_object(clang: Path, names: list[str], out: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        objs = []
        for name in names:
            obj = Path(tmp) / f"{name}.o"
            subprocess.run(
                [str(clang), "-x", "assembler", "-target", "amdgcn-amd-amdhsa",
                 "-mcode-object-version=4", "-mcpu=gfx1010", "-mno-wavefrontsize64",
                 "-c", "-o", str(obj), str(SRC_DIR / f"{name}.s")],
                check=True,
            )
            objs.append(str(obj))
        subprocess.run(
            [str(clang), "-target", "amdgcn-amd-amdhsa", "-Xlinker", "--build-id",
             "-o", str(out), *objs],
            check=True,
        )


TYPES = ("hhh", "hhs", "sss")
LAYOUTS = ("nn", "tn", "nt")
TILES = ("small", "large")
NAME_RE = re.compile(r"_MT(\d+)x(\d+)x(\d+)_.*_WG(\d+)_(\d+)_1$")


def kernel_table(kernels: list[dict]) -> str:
    by_key = {(k["type"], k["layout"], k["tile"]): k["name"] for k in kernels}
    if len(by_key) != len(kernels) or len(by_key) != len(TYPES) * len(LAYOUTS) * len(TILES):
        raise SystemExit("kernels.json needs exactly one kernel per type/layout/tile")
    types = []
    for t in TYPES:
        layouts = []
        for layout in LAYOUTS:
            tiles = []
            for tile in TILES:
                name = by_key[(t, layout, tile)]
                mt0, mt1, depth_u, wg0, wg1 = (int(x) for x in NAME_RE.search(name).groups())
                tiles.append(f'{{"{name}", {mt0}, {mt1}, {depth_u}, {wg0 * wg1}}}')
            layouts.append("{" + ", ".join(tiles) + "}")
        types.append("{" + ",\n  ".join(layouts) + "}")
    return (
        "struct Gfx1010AsmGemmKernel {\n"
        "  const char* name;\n"
        "  unsigned mt0;\n"
        "  unsigned mt1;\n"
        "  unsigned depth_u;\n"
        "  unsigned threads;\n"
        "};\n"
        f"// [{', '.join(TYPES)}][{', '.join(LAYOUTS)}][{', '.join(TILES)}]\n"
        "static const Gfx1010AsmGemmKernel kGfx1010AsmGemmKernels[3][3][2] = {\n "
        + ",\n ".join(types)
        + "};\n"
    )


def write_inc(blob: bytes, kernels: list[dict], out: Path) -> None:
    rows = [",".join(f"0x{b:02x}" for b in blob[i : i + 16]) for i in range(0, len(blob), 16)]
    out.write_text(
        "#pragma once\n"
        "// Generated by tools/pack_gfx1010_asm_gemm.py from kernels.json.\n"
        + kernel_table(kernels)
        + "static const unsigned char kGfx1010AsmGemmHsaco[] = {\n"
        + ",\n".join(rows)
        + "\n};\n"
        + f"static const unsigned int kGfx1010AsmGemmHsacoSize = {len(blob)};\n",
        encoding="utf-8",
        newline="\n",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", type=Path, required=True, help="ROCm clang++ used as the AMDGPU assembler")
    parser.add_argument("--tensile-dir", type=Path, help="Tensile output directory to copy kernel sources from")
    args = parser.parse_args()

    kernels = json.loads((OUT_DIR / "kernels.json").read_text(encoding="utf-8"))
    names = sorted({k["name"] for k in kernels})
    if args.tensile_dir:
        copy_sources(args.tensile_dir, set(names))
    co = OUT_DIR / "gfx1010_asm_gemm.co"
    build_code_object(args.clang, names, co)
    write_inc(co.read_bytes(), kernels, OUT_DIR / "hsaco.inc")
    print(f"{len(names)} kernels, {co.stat().st_size} bytes -> {co}")


if __name__ == "__main__":
    main()
